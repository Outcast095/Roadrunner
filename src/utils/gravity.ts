// Импортируем библиотеку Ammo.js, которая является портом физического движка Bullet Physics для JavaScript/TypeScript
// Эта библиотека позволяет создавать реалистичные физические симуляции в веб-приложениях
import * as Ammo from 'ammo.js';

/**
 * Функция initPhysicsWorld инициализирует физический мир с настроенной гравитацией
 * Эта функция создает все необходимые компоненты для работы физического движка
 * и возвращает готовый к использованию физический мир
 * 
 * @returns {Ammo.btDiscreteDynamicsWorld} Инициализированный физический мир, готовый для добавления объектов
 */
export const initPhysicsWorld = (): Ammo.btDiscreteDynamicsWorld => {
  // Создаем конфигурацию обнаружения столкновений
  // btDefaultCollisionConfiguration содержит настройки по умолчанию для обработки столкновений
  const collisionConfiguration = new Ammo.btDefaultCollisionConfiguration(); 
  
  // Создаем диспетчер столкновений, который будет обрабатывать столкновения между объектами
  // Он использует ранее созданную конфигурацию для определения того, как обрабатывать различные типы столкновений
  const dispatcher = new Ammo.btCollisionDispatcher(collisionConfiguration); 
  
  // Создаем алгоритм широкой фазы обнаружения столкновений
  // btDbvtBroadphase использует динамическое дерево ограничивающих объемов для быстрого определения
  // потенциальных пар объектов, которые могут столкнуться
  const broadphase = new Ammo.btDbvtBroadphase(); 
  
  // Создаем решатель ограничений, который вычисляет, как объекты должны двигаться
  // после столкновения для соблюдения физических законов
  // btSequentialImpulseConstraintSolver - это стандартный решатель для большинства симуляций
  const solver = new Ammo.btSequentialImpulseConstraintSolver(); 
  
  // Создаем сам физический мир, объединяя все созданные компоненты
  // btDiscreteDynamicsWorld - это основной класс, который управляет всей физической симуляцией
  const physicsWorld = new Ammo.btDiscreteDynamicsWorld( 
    dispatcher,    // Диспетчер столкновений
    broadphase,    // Алгоритм широкой фазы
    solver,        // Решатель ограничений
    collisionConfiguration  // Конфигурация столкновений
  ); 
  
  // Устанавливаем стандартную гравитацию для физического мира
  // Вектор (0, -9.81, 0) соответствует земной гравитации:
  // - 0 по оси X (нет горизонтального притяжения)
  // - -9.81 по оси Y (притяжение вниз со стандартным ускорением свободного падения)
  // - 0 по оси Z (нет горизонтального притяжения)
  physicsWorld.setGravity(new Ammo.btVector3(0, -9.81, 0)); 
  
  // Возвращаем инициализированный физический мир для дальнейшего использования
  return physicsWorld;
};


/**
 * Функция setCustomGravity устанавливает пользовательское значение гравитации в физическом мире
 * Это позволяет изменять поведение объектов в симуляции, например, для создания эффектов
 * невесомости, лунной гравитации или других планет
 * 
 * @param {Ammo.btDiscreteDynamicsWorld} physicsWorld - Физический мир, в котором нужно изменить гравитацию
 * @param {number} x - Компонент X вектора гравитации (горизонтальная составляющая по оси X)
 * @param {number} y - Компонент Y вектора гравитации (вертикальная составляющая, обычно отрицательный для симуляции притяжения вниз)
 * @param {number} z - Компонент Z вектора гравитации (горизонтальная составляющая по оси Z)
 */
export const setCustomGravity = (
  physicsWorld: Ammo.btDiscreteDynamicsWorld, // Физический мир, в котором будет изменена гравитация
  x: number = 0,                            // Значение по умолчанию для X - 0 (нет горизонтального притяжения)
  y: number = -9.81,                        // Значение по умолчанию для Y - стандартное земное притяжение
  z: number = 0                             // Значение по умолчанию для Z - 0 (нет горизонтального притяжения)
): void => {
  // Создаем новый трехмерный вектор с указанными компонентами и устанавливаем его как вектор гравитации
  // Это мгновенно изменит поведение всех физических объектов в мире
  physicsWorld.setGravity(new Ammo.btVector3(x, y, z));
};